    /**
     * When each step of each environment's import last succeeded, null where one never has.
     * <p>
     * <b>Every step and not only the model</b>, because the reactions are steps of the same import that run
     * after it, and the documentation of an environment is asked for once its whole chain has run - so a site
     * read as soon as the model is in is a site read before its runtime views exist.
     */
    private List<String> importedAt() {
        JsonPath state = readJson(IMPORT_STATE_PATH);
        List<String> succeededAt = new ArrayList<>();
        for (int environment = 0; environment < ENVIRONMENTS.size(); environment++) {
            succeededAt.addAll(
                    state.getList("[%d].imports.lastSuccessAt".formatted(environment), String.class));
        }
        return succeededAt;
    }

    /** Whether every part of the site is serving something and none of them is waiting for a build. */
    private boolean everyPartIsPublished() {
        JsonPath parts = readJson(PARTS_PATH);
        return parts.getList("part", String.class).size() == 3
               && !parts.getList("publishedAt", String.class).contains(null)
               && !parts.getList("owedABuild", Boolean.class).contains(true);
    }

    /**
     * Waits for the build one of this suite's asks led to, and answers its id. It has to be a newer build than
     * what stood before, so that a run left over from an earlier suite - or from an earlier run against the
     * same containers, which keep their data while they are left running - can never be mistaken for the one
     * just asked for.
     */
    private long awaitSucceededBuildAfter(long previousNewestBuildId, String trigger) {
        String succeededBuildsOfThatTrigger =
                "findAll { it.state == 'SUCCEEDED' && it.trigger == '%s' }.id".formatted(trigger);
        return await().atMost(BUILD_TIMEOUT)
                .pollInterval(Duration.ofSeconds(1))
                .until(() -> history().getList(succeededBuildsOfThatTrigger, Long.class).stream()
                        .filter(id -> id > previousNewestBuildId)
                        .max(Comparator.naturalOrder())
                        .orElse(null), Objects::nonNull);
    }

    /** The newest finished build of that trigger after the given id, whatever became of it, or null. */
    private JsonPath buildAfter(long previousNewestBuildId, String trigger) {
        JsonPath history = history();
        List<Long> ids = history.getList(
                "findAll { it.trigger == '%s' && it.state != 'RUNNING' }.id".formatted(trigger), Long.class);
        return ids.stream()
                .filter(id -> id > previousNewestBuildId)
                .max(Comparator.naturalOrder())
                .map(id -> readJson(BUILDS_PATH + "/" + id))
                .orElse(null);
    }

    /** The published build of one part, which is what the parts endpoint says is being served for it. */
    private long publishedBuildIdOf(String part) {
        return readJson(PARTS_PATH + "/" + part + "/builds")
                .getList("findAll { it.state == 'SUCCEEDED' }.id", Long.class).stream()
                .mapToLong(Long::longValue)
                .max()
                .orElseThrow();
    }

    /** The newest build of the site, or zero when it has never been built - the ids come from a sequence. */
    private long newestBuildId() {
        return buildIds().stream().mapToLong(Long::longValue).max().orElse(0);
    }

    private List<Long> buildIds() {
        return history().getList("id", Long.class);
    }

    /** The build history of every part of the site, newest first, read with the role that may read it. */
    private JsonPath history() {
        return given().baseUri(DOC_BASE_URL)
                .auth().oauth2(operatorToken())
                .queryParam("limit", 100)
                .when()
                .get(BUILDS_PATH)
                .then()
                .statusCode(200)
                .extract()
                .jsonPath();
    }

