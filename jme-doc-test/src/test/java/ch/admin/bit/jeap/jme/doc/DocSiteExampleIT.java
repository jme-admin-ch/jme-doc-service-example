/**
 * Generates the documentation site of this example out of a stubbed architecture model, and reads what the
 * generator did - over the API and, where only a browser can tell, in a browser.
 * <p>
 * This is the half of the doc service that publishes rather than receives, and it is what makes the example
 * need Node and a Chrome: the site is generated by running the site generator as a child process. So this is
 * the suite that fails when the local development environment is not set up - if the doc service never becomes
 * ready here, its {@code jeap.doc.build.*} configuration is where to look, and {@code docs/local-development.md}
 * says what it has to point at.
 * <p>
 * <b>The whole chain, in the order a landscape travels it</b>: an operator asks for the upstreams to be
 * imported, the import stores what they answer and asks for every part of the site, the parts are generated
 * and published, and the pages are then read by a browser that never authenticated itself. Both upstreams are
 * the stub of this example rather than an architecture repository and a reaction observer - see the
 * {@code jme-doc-upstream-stub} module for what it holds and why it exists.
 * <p>
 * <b>Two upstreams, and the second one is what the runtime views are drawn from</b>: the reactions are steps
 * of the same import, they run after the model because every observed name is resolved against it, and the
 * documentation of an environment is asked for once its whole chain has run. Every environment of this site
 * reads both, so every tree of it carries the landscape and its runtime views.
 * <p>
 * <b>A site is published as one build per part</b>: the <i>shell</i>, which carries the site's own pages and
 * everything no system claims, plus one part per system of the model. The stubbed landscape has two systems,
 * so this site has three parts - and they are built one after another, because
 * {@code jeap.doc.build.max-concurrent-parts} is 1 in this instance.
 * <p>
 * <b>Both halves of the hybrid model end up on it</b>: what the generator writes out of the model, and what a
 * team uploads next to its code. The upload is driven here rather than in the API suite because this is where a
 * build can be waited for - the example publishes the stubbed landscape alone, so one is quick - and seeing the
 * page served is the only thing that says an upload was published rather than only stored.
 * <p>
 * <b>Administering a site is not a system's own business.</b> The upload roles carry the system in their tenant
 * part so that a pipeline can only change its own documentation, while a build regenerates a part with the
 * documentation of every repository in it - so it is granted on a resource of its own that no pipeline holds.
 * <p>
 * The tests are ordered because they are one story. That several triggers collapse into a single build is not
 * asserted here - that is the doc service's own behaviour and is covered there. This suite is about the
 * instance being wired up correctly.
 */
